"""Test of tools/lifter/build_opt.py's SPLIT path (linux-arm64): the functions too long to optimise are compiled in a
translation unit of their own at -O0 and joined to the rest of their file with ld.lld -r, instead of `optnone` in the file.

    python tests/build_opt_split_test.py            fake compiler: split_source, the ladder, the reservations, the budget
    RECOMP_CLANG=<clang> python tests/build_opt_split_test.py --real
                                                     also a real compile of a small lifted-style file for aarch64 (needs a
                                                     clang with the aarch64 target and ld.lld beside it); the joined object
                                                     must define every function once, the long one compiled at -O0

Checks: part a + part b hold every function of the source exactly once, in source order, with the file's comment and
#include lines on top of both, one-line wrappers in part a; a file with no long function is compiled as it is (no parts);
the ladder of a file like c_00a3.c (one function of 215,493 statements) ends at step 0 (no WHOLE FILE -O0), its part b at
-O0 joined with ld.lld -r; the reservations stay within the budget and are given back; the budget leaves Steam's share
(RECOMP_MEM_RESERVE, 3.5 GB) on top of 4 GB and never exceeds what is available less 1 GB.
"""
import os
import re
import subprocess
import sys
import tempfile
import threading
import types

HERE = os.path.dirname(os.path.abspath(__file__))
LIFTER = os.path.join(HERE, '..', 'tools', 'lifter')
GB = 1 << 30
HEAD = '/* generated by recomp_eh.py -- do not edit */\n#include "runtime.h"\n#include "funcs.h"\n\n'


def fn(name, n, two=False):
    """A function of the generated shape with n statements (lines between the opening and the closing line)."""
    if two:
        return 'void u_%s(Ctx *c, uint64_t rp) {\n' % name + ''.join('L_%x: c->x[0] = %dULL;\n' % (i * 4, i) for i in range(n)) + '}\nvoid f_%s(Ctx *c) { u_%s(c, 0); }\n' % (name, name)
    return 'void f_%s(Ctx *c) {\n' % name + ''.join('L_%x: c->x[0] = %dULL;\n' % (i * 4, i) for i in range(n)) + '}\n'


def load(avail=None):
    os.environ['RECOMP_TARGET'] = 'linux-arm64'
    os.environ['RECOMP_INLINE'] = '1'
    b = types.ModuleType('build')
    b.TARGET_ARM64 = True
    b.CODEGEN_FLAGS = []
    sys.modules['build'] = b
    sys.modules['build_nro'] = types.ModuleType('build_nro')
    sys.path.insert(0, LIFTER)
    import build_opt as B
    B.ram_bytes = lambda: 15 * GB + 300 * (1 << 20)        # the Frame: 15.3 GB as Linux reports it
    B.mem_available = lambda: avail if avail is not None else 12 * GB
    B.SPLIT = B.SPLIT_WANTED
    return B


def check_split(B, bad):
    d = tempfile.mkdtemp()
    src = os.path.join(d, 'c_0001.c')
    parts = [fn('7100000000', 10), fn('7100000100', 50, two=True), fn('7100000200', 5), fn('7100000300', 80)]
    with open(src, 'w') as f:
        f.write(HEAD + '\n'.join(parts))
    a, b, count, lines = B.split_source(src, os.path.join(d, 'c_0001.obj'), 20)
    ta, tb = open(a).read(), open(b).read()
    if not (ta.startswith(HEAD.rstrip('\n')) and tb.startswith(HEAD.rstrip('\n'))):
        bad.append('the head lines are not on top of both parts')
    names = lambda t: re.findall(r'^void (\w+)\(.*\) \{', t, re.M)          # definitions (not part a's declarations)
    if names(ta) != ['f_7100000000', 'f_7100000100', 'f_7100000200'] or names(tb) != ['u_7100000100', 'f_7100000300']:
        bad.append('split names: a %r b %r' % (names(ta), names(tb)))
    if 'void f_7100000100(Ctx *c) { u_7100000100(c, 0); }' not in ta:
        bad.append('the one-line wrapper is not in part a')
    if 'void u_7100000100(Ctx *c, uint64_t rp);\n' not in ta or 'void f_7100000300(Ctx *c);\n' not in ta:
        bad.append('part a does not declare the functions moved to part b')
    if (count, lines) != (2, 130):
        bad.append('count %r lines %r' % (count, lines))
    body = lambda t: sorted(re.findall(r'^void \w+\(Ctx \*c(?:, uint64_t rp)?\) \{\n.*?^\}\n', t, re.M | re.S))
    if body(ta) + body(tb) != sorted(body(open(src).read())) or len(body(ta) + body(tb)) != 4:
        bad.append('the functions of a + b are not those of the source')
    if B.split_source(src, os.path.join(d, 'c_0001.obj'), 100)[0] is not None or os.path.exists(a):
        bad.append('no long function: parts made or old parts left')
    st = os.path.join(d, 'c_0002.c')
    with open(st, 'w') as f:
        f.write(HEAD + 'static ' + fn('7100000400', 50) + 'void f_7100000500(Ctx *c) { f_7100000400(c); }\n')
    r = B.split_source(st, os.path.join(d, 'c_0002.obj'), 20)
    lf = B.long_functions(st, os.path.join(d, 'c_0002.obj'), 20)
    if r[0] is not None or r[2] != -1 or lf[2] is None or lf[4] != 1:
        bad.append('a long static function is split (part a could not call it): %r %r' % (r, lf))
    return d


def check_ladder(B, bad):
    """c_00a3.c-like (one long function over every time limit when it is in the file) and a small file, with a fake clang."""
    d = tempfile.mkdtemp()
    with open(os.path.join(d, 'huge.c'), 'w') as f:
        f.write(HEAD + fn('7100100000', 30000) + fn('7100200000', 300) + fn('7100300000', 200))
    with open(os.path.join(d, 'small.c'), 'w') as f:
        f.write(HEAD + fn('7100400000', 300))
    calls, lock = [], threading.Lock()

    def fake_run_limited(cmd, limit, mem=0):
        src, obj = cmd[-3], cmd[-1]
        long_fn = 'void f_7100100000(Ctx *c) {' in open(src).read()     # defined there (part a only declares it)
        opt = cmd[2]
        with lock:
            calls.append((os.path.basename(src), opt, mem, limit))
            assert B._mem_used <= B.MEM_BUDGET, 'reservations over the budget'
        if long_fn and opt != '-O0':
            return None, '', 0.001                        # the long function at -O2 (optnone or not): over the time limit
        open(obj, 'w').close()
        return 0, '', 0.001

    class Done:
        returncode, stdout, stderr = 0, '', ''

    def fake_run(cmd, **kw):
        with lock:
            calls.append(('lld' if cmd[0] == B.LLD else os.path.basename(cmd[-3]), cmd[1], None, None))
        if cmd[0] == B.LLD:
            open(cmd[-1], 'w').close()
        return Done()

    B.run_limited = fake_run_limited
    B.subprocess = types.SimpleNamespace(run=fake_run)
    B.INLINE = False
    r = B.compile_file(os.path.join(d, 'huge.c'), os.path.join(d, 'huge.obj'), [])
    r2 = B.compile_file(os.path.join(d, 'small.c'), os.path.join(d, 'small.obj'), [])
    seq = [(c[0], c[1]) for c in calls]
    want = [('huge.split_a.c', '-O2'), ('huge.split_b.c', '-O0'), ('lld', '-r'), ('small.c', '-O2')]
    if seq != want:
        bad.append('compiles %r, expected %r' % (seq, want))
    if r[0] or 'WHOLE FILE' in r[3] or 'unit of their own' not in r[3]:
        bad.append('huge: %r' % (r,))
    if r2[0] or r2[3]:
        bad.append('small: %r' % (r2,))
    for n in ('huge.split_a.c', 'huge.split_b.c', 'huge.part_a.o', 'huge.part_b.o'):
        if os.path.exists(os.path.join(d, n)):
            bad.append('%s left behind' % n)
    if not os.path.exists(os.path.join(d, 'huge.obj')):
        bad.append('no joined object')
    if any(c[3] is not None for c in calls if c[0] == 'huge.split_b.c'):
        bad.append('part b (plain -O0) has a time limit')
    # RECOMP_INLINE on linux-arm64 -O2 (INLINE_ONE_TRY): one compile per part; part a with the inlined helpers, part b
    # (-O0) without them
    del calls[:]
    seen = []
    real = B.run_limited
    B.run_limited = lambda cmd, limit, mem=0: (seen.append(B.INLINE_FLAG in cmd), real(cmd, limit, mem))[1]
    B.INLINE = True
    r3 = B.compile_file_inline(os.path.join(d, 'huge.c'), os.path.join(d, 'huge2.obj'), [])
    if not B.INLINE_ONE_TRY or r3[0] or [(c[0], c[1]) for c in calls] != [('huge2.split_a.c', '-O2'), ('huge2.split_b.c', '-O0'), ('lld', '-r')] or seen != [True, False]:
        bad.append('one inlined try: %r %r %r' % (r3, calls, seen))
    # part b's join fails: the whole file at -O0 (as before SPLIT), not recorded in _ladder.json
    B.INLINE = False
    B.run_limited = fake_run_limited

    class Fail:
        returncode, stdout, stderr = 1, '', 'ld.lld: error: broken'
    B.subprocess = types.SimpleNamespace(run=lambda cmd, **kw: Fail() if cmd[0] == B.LLD else (open(cmd[-1], 'w').close(), Done())[1])
    r4 = B.compile_file(os.path.join(d, 'huge.c'), os.path.join(d, 'huge3.obj'), [])
    if r4[0] or 'WHOLE FILE' not in r4[3] or 'split failed' not in r4[3] or 'huge3.obj' in B.ladder(d):
        bad.append('a failed join: %r %r' % (r4, B.ladder(d)))
    for n in ('huge3.split_a.c', 'huge3.split_b.c', 'huge3.part_a.o', 'huge3.part_b.o'):
        if os.path.exists(os.path.join(d, n)):
            bad.append('%s left behind after the whole-file fallback' % n)
    if B._mem_used:
        bad.append('reservations not given back: %d' % B._mem_used)
    return d


def check_budget(bad):
    B = load(avail=12 * GB)
    B.limit_memory(3)
    if abs(B.MEM_BUDGET - (15 * GB + 300 * (1 << 20) - 4 * GB - int(3.5 * GB))) > 1:
        bad.append('budget with 12 GB available: %.2f GB' % (B.MEM_BUDGET / GB))
    B.mem_available = lambda: 5 * GB                       # the game running beside the build
    B.limit_memory(3)
    if B.MEM_BUDGET != 4 * GB or B.MEM_LIMIT != 4 * GB:
        bad.append('budget with 5 GB available: %.2f GB (expected 4)' % (B.MEM_BUDGET / GB))
    if B.MEM_KEY[0] == B.MEM_BUDGET:
        bad.append('the ladder key follows what was free at the start')
    return B


def check_real(bad):
    """A real aarch64 compile of a small lifted-style file through compile_file (RECOMP_CLANG)."""
    clang = os.environ.get('RECOMP_CLANG')
    if not clang:
        bad.append('--real needs RECOMP_CLANG')
        return
    import importlib
    B = load()
    importlib.reload(B)
    B.ram_bytes = lambda: 15 * GB
    B.mem_available = lambda: 12 * GB
    B.SPLIT = True
    B.OPTNONE_LINES = 40
    B.INLINE = False
    B.limit_memory(1)
    d = tempfile.mkdtemp()
    with open(os.path.join(d, 'runtime.h'), 'w') as f:
        f.write('typedef unsigned long long uint64_t;\ntypedef struct Ctx { uint64_t x[32]; uint64_t fn; } Ctx;\n')
    with open(os.path.join(d, 'funcs.h'), 'w') as f:
        f.write('void f_7100000000(Ctx *c);\nvoid f_7100000100(Ctx *c);\nvoid f_7100000200(Ctx *c);\n')   # (no u_: see split_source)
    src = os.path.join(d, 'c_0001.c')
    with open(src, 'w') as f:      # the long u_ (part b) calls f_7100000200 (part a); its wrapper (part a) calls it back
        f.write(HEAD + fn('7100000100', 50, two=True).replace('}\nvoid f_', '  f_7100000200(c);\n}\nvoid f_', 1)
                + fn('7100000000', 50) + fn('7100000200', 10))
    flags = ['--target=aarch64-linux-gnu', '-w', '-fno-strict-aliasing', '-I', d]
    r = B.compile_file(src, os.path.join(d, 'c_0001.obj'), flags, 60, ['-ffp-contract=off'])
    if r[0]:
        bad.append('real compile: %r' % (r,))
        return
    nm = os.path.join(os.path.dirname(clang), 'llvm-nm')
    nm = nm if os.path.exists(nm) else 'nm'                 # (SteamOS has clang without llvm-nm; binutils' nm reads the object too)
    obj = os.path.join(d, 'c_0001.obj')
    syms = subprocess.run([nm, '--defined-only', obj], capture_output=True, text=True).stdout.split()
    undef = subprocess.run([nm, '-u', obj], capture_output=True, text=True).stdout.split()
    for s in ('f_7100000000', 'f_7100000100', 'u_7100000100', 'f_7100000200'):
        if syms.count(s) != 1:
            bad.append('symbol %s: %d definitions in the joined object' % (s, syms.count(s)))
        if s in undef:
            bad.append('symbol %s undefined in the joined object' % s)
    if 'unit of their own' not in r[3]:
        bad.append('real: not split as expected: %r' % (r,))
    print('real: %s; joined object: %s' % (r[3], ' '.join(s for s in syms if s.startswith(('f_', 'u_')))))


def main():
    bad = []
    if len(sys.argv) > 1 and sys.argv[1] == '--child-budget':
        check_budget(bad)
    elif len(sys.argv) > 1 and sys.argv[1] == '--child-real':
        check_real(bad)
    elif len(sys.argv) > 1 and sys.argv[1] == '--child':
        B = load()
        B.limit_memory(3)
        check_split(B, bad)
        check_ladder(B, bad)
    else:
        rc = 0
        for what in ['--child', '--child-budget'] + (['--child-real'] if '--real' in sys.argv else []):
            rc |= subprocess.call([sys.executable, os.path.abspath(__file__), what])
        print('build_opt split test: %s' % ('ok' if not rc else 'FAILED'))
        return rc
    for b in bad:
        print('FAILED: ' + b)
    print('%s %s' % (sys.argv[1], 'ok' if not bad else 'FAILED'))
    return 1 if bad else 0


if __name__ == '__main__':
    sys.exit(main())
